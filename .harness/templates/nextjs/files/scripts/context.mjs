#!/usr/bin/env node
// Generates context/: a compact orientation layer for an app using the harness
// layout (src/{app,experimental,features,components,core,config}).
//   context/README.md  start map: areas, status summary, routes  (read first)
//   context/status.md  every "Open work" item, grouped           (on demand)
//   context/files.md   every source file and its exports          (on demand)
// context/ is generated, not committed: `npm run setup` and the session-start
// hook write it. Usage: node scripts/context.mjs [app-dir] [--print]
// --print writes the start map to stdout (for a session-start hook) and the
// progress lines to stderr.
import {
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  statSync,
  writeFileSync,
} from 'node:fs';
import { spawnSync } from 'node:child_process';
import { basename, join, relative, sep } from 'node:path';
import { formatText } from './format-output.mjs';

const appDir =
  process.argv.slice(2).find((arg) => !arg.startsWith('--')) ?? '.';
const print = process.argv.includes('--print');
const log = print ? console.error : console.log;
const src = join(appDir, 'src');
const outDir = join(appDir, 'context');
const MAX_EXPORTS = 6;
const HEADER =
  '<!-- Generated by `npm run context` from the code and its README files. Do not edit. -->';

const posix = (p) => p.split(sep).join('/');
const rel = (p) => posix(relative(appDir, p));
const isDir = (p) => existsSync(p) && statSync(p).isDirectory();
const dirs = (p) =>
  isDir(p)
    ? readdirSync(p, { withFileTypes: true })
        .filter((e) => e.isDirectory())
        .map((e) => e.name)
        .sort()
    : [];
function walk(p, files = []) {
  if (!isDir(p)) return files;
  for (const e of readdirSync(p, { withFileTypes: true }).sort((a, b) =>
    a.name.localeCompare(b.name),
  )) {
    if (e.name === 'node_modules' || e.name.startsWith('.')) continue;
    const full = join(p, e.name);
    if (e.isDirectory()) walk(full, files);
    else files.push(full);
  }
  return files;
}
const isCode = (f) => /\.(ts|tsx|mjs|js)$/.test(f) && !/\.d\.m?ts$/.test(f);
const isTest = (f) => /\.(test|spec)\.(ts|tsx|mjs|js)$/.test(f);
const stem = (f) =>
  basename(f).replace(/\.(browser\.)?(test|spec)?\.?(tsx?|mjs|js)$/, '');

// --- README documents ------------------------------------------------------
function section(text, heading) {
  const lines = text.split('\n');
  const start = lines.findIndex(
    (l) => l.trim().toLowerCase() === `## ${heading}`,
  );
  if (start < 0) return '';
  const end = lines.findIndex((l, i) => i > start && /^## /.test(l));
  return lines
    .slice(start + 1, end < 0 ? undefined : end)
    .join('\n')
    .trim();
}
function sentence(text, max = 150) {
  const clean = text
    .replace(/\[([^\]]+)\]\([^)]*\)/g, '$1')
    .replace(/\*\*/g, '')
    .replace(/^\s*[-*]\s+/, '')
    .replace(/\s+/g, ' ')
    .trim();
  const m = clean.match(new RegExp(`^(.{15,${max}}?[.!?])(\\s|$)`));
  if (m) return m[1];
  return clean.length <= max
    ? clean
    : clean.slice(0, max).replace(/\s+\S*$/, '') + '…';
}
// An open item starts with its state in bold (docs/FORMAT.md).
const STATE = /^(Next|In progress|Waiting on ([^:*.]+)|To decide)\s*[:.]?\s*/i;
const ORDER = ['In progress', 'Next', 'Waiting', 'To decide', 'Unlabelled'];

/** The date each line was last changed, from Git; empty outside a repository. */
function lineDates(file) {
  const result = spawnSync(
    'git',
    ['blame', '--line-porcelain', '--', relative(appDir, file)],
    { cwd: appDir, encoding: 'utf8' },
  );
  if (result.status !== 0) return [];
  const dates = [];
  for (const line of result.stdout.split('\n'))
    if (line.startsWith('committer-time '))
      dates.push(
        new Date(Number(line.slice(15)) * 1000).toISOString().slice(0, 10),
      );
  return dates;
}

function readDoc(folder) {
  const file = join(folder, 'README.md');
  if (!existsSync(file)) return null;
  const text = readFileSync(file, 'utf8');
  const lines = text.split('\n');
  const purpose = sentence(
    section(text, 'what it does') || lines.slice(1).join(' '),
  );
  const startWith = (text.match(/^Start with:\s*(.+)$/m) ?? [])[1] ?? '';
  const dates = lineDates(file);
  const open = [];
  let inOpen = false;
  for (let i = 0; i < lines.length; i += 1) {
    if (/^## /.test(lines[i])) inOpen = /^## open work\s*$/i.test(lines[i]);
    if (!inOpen || !/^[-*] /.test(lines[i])) continue;
    let end = i + 1;
    while (end < lines.length && /^\s+\S/.test(lines[end])) end += 1;
    const flat = lines
      .slice(i, end)
      .join(' ')
      .replace(/^[-*]\s+/, '')
      .replace(/\s+/g, ' ');
    const bold = (flat.match(/^\*\*([^*]+?)\*\*/) ?? [])[1] ?? '';
    const label = bold.match(STATE);
    const kind = !label
      ? 'Unlabelled'
      : /^waiting/i.test(label[1])
        ? 'Waiting'
        : ORDER.find((o) => o.toLowerCase() === label[1].toLowerCase());
    const title = label ? bold.slice(label[0].length).replace(/[:.]$/, '') : '';
    const rest = flat.replace(/^\*\*[^*]+\*\*\s*/, '');
    open.push({
      state: kind,
      who: label?.[2]?.trim() ?? '',
      title,
      text: sentence(rest || flat, 140),
      since: dates[i] ?? '',
    });
  }
  return { file: rel(file), purpose, startWith, open };
}

// --- Code -------------------------------------------------------------------
function exportsOf(file) {
  const text = readFileSync(file, 'utf8');
  const names = new Set();
  for (const m of text.matchAll(
    /^export\s+(?:default\s+)?(?:async\s+)?(?:function\*?|const|let|class|type|interface|enum)\s+([A-Za-z_$][\w$]*)/gm,
  ))
    names.add(m[1]);
  for (const m of text.matchAll(/^export\s+(?:type\s+)?\{([^}]+)\}/gm))
    for (const part of m[1].split(','))
      names.add(
        part
          .trim()
          .split(/\s+as\s+/)
          .pop()
          .replace(/^type\s+/, ''),
      );
  if (/^export\s+default\s+(?!async|function|class)/m.test(text))
    names.add('default');
  if (/^export\s+\*\s+from/m.test(text)) names.add('*');
  return [...names].filter(Boolean);
}
const fmtExports = (names) =>
  names.slice(0, MAX_EXPORTS).join(', ') +
  (names.length > MAX_EXPORTS ? `, +${names.length - MAX_EXPORTS}` : '');

function areaOf(path) {
  const p = posix(relative(src, path));
  if (p.startsWith('..')) return null;
  const [top, second] = p.split('/');
  if (top === 'features' || top === 'experimental')
    return second && !second.includes('.') ? `${top}/${second}` : null;
  if (['app', 'core', 'components', 'config'].includes(top)) return top;
  return /^(proxy|middleware|instrumentation)\./.test(top) ? 'app' : null;
}

// Tests: attributed to the area they import most, and to a source file only
// when their base name matches it (tests/order-list.test.ts ↔ order-list.ts).
const tests = [...walk(join(appDir, 'tests')), ...walk(src)].filter(isTest);
const testsByArea = new Map();
const testsByStem = new Map();
for (const t of tests) {
  const counts = new Map();
  const text = readFileSync(t, 'utf8');
  for (const m of text.matchAll(
    /from\s+['"]([^'"]+)['"]|import\(\s*['"]([^'"]+)['"]/g,
  )) {
    const spec = m[1] ?? m[2];
    const target = spec.startsWith('@/')
      ? join(src, spec.slice(2))
      : spec.startsWith('.')
        ? join(t, '..', spec)
        : null;
    const area = target && areaOf(target);
    if (area) counts.set(area, (counts.get(area) ?? 0) + 1);
  }
  const own = areaOf(t);
  // Registries in src/config are imported alongside what they configure, so
  // they win only when a test imports nothing else.
  const ranked = [...counts].sort(
    (a, b) => b[1] - a[1] || (a[0] === 'config') - (b[0] === 'config'),
  );
  const primary = own ?? ranked[0]?.[0] ?? null;
  if (primary) {
    if (!testsByArea.has(primary)) testsByArea.set(primary, []);
    testsByArea.get(primary).push(rel(t));
  }
  if (!testsByStem.has(stem(t))) testsByStem.set(stem(t), []);
  testsByStem.get(stem(t)).push(rel(t));
}

// Feature dependencies: src/config/features.json, else eslint.config.mjs.
let featureDeps = {};
const depsFile = join(appDir, 'src/config/features.json');
if (existsSync(depsFile))
  featureDeps = JSON.parse(readFileSync(depsFile, 'utf8'));
else if (existsSync(join(appDir, 'eslint.config.mjs'))) {
  const m = readFileSync(join(appDir, 'eslint.config.mjs'), 'utf8').match(
    /featureDependencies\s*=\s*\{([\s\S]*?)\n\};/,
  );
  if (m)
    for (const line of m[1].matchAll(/^\s*([\w-]+):\s*\[([^\]]*)\]/gm))
      featureDeps[line[1]] = [...line[2].matchAll(/'([^']+)'/g)].map(
        (x) => x[1],
      );
}

// --- Areas -------------------------------------------------------------------
const areas = [
  ['app', src, null],
  ['core', join(src, 'core'), null],
  ['components', join(src, 'components'), null],
  ['config', join(src, 'config'), null],
];
for (const layer of ['features', 'experimental'])
  for (const d of dirs(join(src, layer))) {
    areas.push([`${layer}/${d}`, join(src, layer, d), null]);
    for (const p of dirs(join(src, layer, d)))
      if (existsSync(join(src, layer, d, p, 'README.md')))
        areas.push([
          `${layer}/${d}/${p}`,
          join(src, layer, d, p),
          `${layer}/${d}`,
        ]);
  }
const docs = new Map(areas.map(([n, f]) => [n, readDoc(f)]));

// --- context/status.md ---------------------------------------------------------
const items = [];
for (const [name, doc] of docs)
  for (const item of doc?.open ?? []) items.push({ name, ...item });
const heading = (item) =>
  item.state === 'Waiting' ? `Waiting on ${item.who}` : item.state;
const groups = new Map();
for (const item of [...items].sort(
  (a, b) => ORDER.indexOf(a.state) - ORDER.indexOf(b.state),
)) {
  const key = heading(item);
  if (!groups.has(key)) groups.set(key, []);
  groups.get(key).push(item);
}
const line = (i) =>
  `- ${i.name}: ${i.title ? `**${i.title}.** ` : ''}${i.text}${i.since ? ` _(since ${i.since})_` : ''}`;
const statusLines = [
  '# Status',
  '',
  HEADER,
  '',
  'Every "Open work" item, by state, oldest first within a state. The README',
  'named on each line has the outcome, dependency and proof.',
  '',
];
for (const [key, group] of groups)
  statusLines.push(
    `## ${key}`,
    '',
    ...[...group]
      .sort((a, b) => (a.since || '9').localeCompare(b.since || '9'))
      .map(line),
    '',
  );

// --- context/files.md ----------------------------------------------------------
const fileLines = [
  '# Files',
  '',
  HEADER,
  '',
  `Every source file by area, with up to ${MAX_EXPORTS} exports and its matching test.`,
  'Search this file for a name before searching the code.',
  '',
];
for (const [name, folder, parent] of areas) {
  if (parent) continue; // parts are listed inside their feature
  const files = walk(folder).filter(
    (f) =>
      isCode(f) &&
      !isTest(f) &&
      areaOf(f) === name &&
      !(name === 'app' && !posix(relative(src, f)).match(/^(app\/|[\w-]+\.)/)),
  );
  if (!files.length) continue;
  fileLines.push(`## ${name}`, '');
  for (const f of files) {
    const ex = fmtExports(exportsOf(f));
    const t = testsByStem.get(stem(f));
    fileLines.push(
      `- \`${posix(relative(folder, f))}\`${ex ? `: ${ex}` : ''}${t ? ` · test ${t.map((x) => `\`${x}\``).join(', ')}` : ''}`,
    );
  }
  fileLines.push('');
}

// --- context/README.md (start map) ---------------------------------------------
const start = [
  '# Context',
  '',
  HEADER,
  '',
  'Read this first in a new session. It says what exists, where it lives and',
  'what is open, so a task can go straight to the README and files it needs.',
  'On demand: [status](status.md) lists every open item; [files](files.md)',
  'lists every source file with its exports.',
  '',
  '## Areas',
  '',
  'Dependencies point down: app → experimental → features → components → core → config.',
  '',
  '| Area | What it is | Start with | Uses | Tests | Open |',
  '| --- | --- | --- | --- | --- | --- |',
];
for (const [name, , parent] of areas) {
  if (name === 'app' || name === 'config' || name === 'components') continue;
  const doc = docs.get(name);
  const feature =
    name.startsWith('features/') && !parent ? name.split('/')[1] : null;
  const uses = feature ? (featureDeps[feature] ?? []).join(', ') || '' : '';
  const label = parent ? `↳ ${name.split('/').pop()}` : name;
  const link = doc ? `[${label}](../${doc.file})` : label;
  const nTests = parent ? '' : (testsByArea.get(name) ?? []).length || '';
  const open = doc?.open.length || '';
  start.push(
    `| ${link} | ${(doc?.purpose ?? '').replace(/\|/g, '/')} | ${(doc?.startWith ?? '').replace(/\|/g, '/')} | ${uses} | ${nTests} | ${open} |`,
  );
}
start.push('');
if (items.length) {
  const counts = [...groups].map(
    ([key, g]) => `${g.length} ${key.toLowerCase()}`,
  );
  start.push(
    '## Status',
    '',
    `${counts.join(' · ')}. Full list: [status](status.md).`,
    '',
  );
  for (const key of ['In progress', 'Next'])
    if (groups.has(key))
      start.push(
        `${key}:`,
        '',
        ...groups.get(key).map((i) => `- ${i.name}: ${i.title || i.text}`),
        '',
      );
}
const appDirPath = join(src, 'app');
const routes = walk(appDirPath).filter((f) =>
  /\/(page|route)\.(tsx?|jsx?)$/.test(posix(f)),
);
if (routes.length) {
  start.push('## Entry points', '');
  for (const r of routes) {
    const url =
      '/' +
      posix(relative(appDirPath, r))
        .split('/')
        .slice(0, -1)
        .filter((s) => !/^\(.*\)$/.test(s))
        .join('/');
    start.push(
      `- \`${url}\`${/\/route\./.test(posix(r)) ? ' (API)' : ''}: \`${rel(r)}\``,
    );
  }
  for (const a of walk(appDirPath).filter((f) =>
    /(^|\/)(actions|[\w-]+-actions)\.ts$/.test(posix(f)),
  ))
    start.push(`- Server Actions \`${rel(a)}\`: ${fmtExports(exportsOf(a))}`);
  start.push('');
}

// --- Write ---------------------------------------------------------------------
// Formatted with the application's Prettier when it is installed. context/ is
// ignored by Git, and so by Prettier, so a fresh clone without dependencies
// can still produce the map for a session.
const outputs = {
  'README.md': start,
  'status.md': statusLines,
  'files.md': fileLines,
};
mkdirSync(outDir, { recursive: true });
for (const [name, lines] of Object.entries(outputs)) {
  const path = join(outDir, name);
  const content = await formatText(appDir, path, lines.join('\n'), {
    optional: true,
  });
  writeFileSync(path, content);
  log(
    `${rel(path)}: ${content.split('\n').length} lines, ~${Math.round(content.length / 4)} tokens`,
  );
  if (print && name === 'README.md') process.stdout.write(content);
}
