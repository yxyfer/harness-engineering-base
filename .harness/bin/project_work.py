"""Derived navigation and reversible complete-plan archiving."""

from __future__ import annotations

import os
import json
from pathlib import Path
import re
from urllib.parse import quote, unquote

from project_records import Plan, WorkError, read_project, safe_path
from source_paths import walk_files

BEGIN = "<!-- project:tasks:start -->"
END = "<!-- project:tasks:end -->"


def link(source: Path, target: Path) -> str:
    return quote(os.path.relpath(target, source.parent), safe="/-.")


def progress(plan: Plan) -> str:
    return (
        f"{sum(t.status == 'complete' for t in plan.tasks)}/{len(plan.tasks)}"
    )


def next_task(plan: Plan) -> str:
    incomplete = [t for t in plan.tasks if t.status != "complete"]
    if not incomplete:
        return "Closed" if plan.status != "superseded" else "Superseded"
    task = next((t for t in incomplete if t.status == "ready"), incomplete[0])
    next_action = f"{task.id}: {task.status}"
    blockers = [t.id for t in incomplete if t.status == "blocked" and t != task]
    return next_action + (
        f"; blocked: {', '.join(blockers)}" if blockers else ""
    )


def plan_table(path: Path, plans: list[Plan]) -> str:
    rows = [
        "| Plan | Adds | Complete | State | Next |",
        "| --- | --- | --- | --- | --- |",
    ]
    for plan in plans:
        rows.append(
            f"| [{plan.id} — {plan.title}]({link(path, plan.path)}) | "
            f"{plan.outcome} | {progress(plan)} | {plan.status} | "
            f"{next_task(plan)} |"
        )
    return "\n".join(rows) + "\n"


def task_table(plan: Plan) -> str:
    rows = ["| Task | Adds | State | Depends on |", "| --- | --- | --- | --- |"]
    for task in plan.tasks:
        rows.append(
            f"| [{task.id} — {task.title}]({link(plan.path, task.path)}) | "
            f"{task.outcome} | {task.status} | "
            f"{', '.join(task.dependencies) or 'none'} |"
        )
    return f"{BEGIN}\n" + "\n".join(rows) + f"\n{END}\n"


def index_outputs(root: Path, plans: list[Plan]) -> dict[Path, str]:
    project = root / "project"
    outputs = {}
    for location, title in (("plans", "Plans"), ("archive", "Archive")):
        path = project / location / "README.md"
        selected = [p for p in plans if p.path.parent.parent.name == location]
        outputs[path] = (
            f"# {title}\n\nGenerated by `./harness project sync`. "
            "Task records own status.\n\n" + plan_table(path, selected)
        )
    path = project / "README.md"
    outputs[path] = (
        "# Project\n\n[Plans](plans/README.md) · "
        "[Architecture](architecture/README.md)\n"
        "[Archive](archive/README.md) · [Format](FORMAT.md)\n\n"
        "Generated by `./harness project sync`. Task records own progress.\n\n"
        + plan_table(path, plans)
    )
    for plan in plans:
        text = plan.path.read_text()
        block = task_table(plan)
        if BEGIN in text or END in text:
            if text.count(BEGIN) != 1 or text.count(END) != 1:
                raise WorkError(f"invalid generated task block: {plan.path}")
            text = re.sub(
                re.escape(BEGIN) + r".*?" + re.escape(END) + r"\n?",
                lambda _: block,
                text,
                flags=re.DOTALL,
            )
        else:
            text = text.rstrip() + "\n\n## Tasks\n\n" + block
        outputs[plan.path] = text
    return outputs


def check_indexes(root: Path) -> None:
    root = root.resolve()
    plans = read_project(root)
    if not (root / "project/FORMAT.md").exists():
        return
    for path, expected in index_outputs(root, plans).items():
        safe_path(root, path)
        if not path.is_file() or path.read_text() != expected:
            raise WorkError(f"stale index: {path}; run ./harness project sync")


def sync_indexes(root: Path) -> None:
    root = root.resolve()
    plans = read_project(root)
    if not (root / "project/FORMAT.md").exists():
        raise WorkError("project/ not present; create from project templates")
    for path, text in index_outputs(root, plans).items():
        safe_path(root, path)
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)


def rewritten_links(root: Path, before: Path, after: Path) -> dict[Path, str]:
    outputs = {}
    excludes = [
        ".git",
        ".venv",
        "node_modules",
        ".harness/tmp",
        ".harness/reports",
        ".next",
        "__pycache__",
    ]
    pattern = re.compile(r"(?<!!)\[[^\]]+\]\(([^)]+)\)")
    for path in walk_files(root, excludes):
        if path.suffix != ".md":
            continue
        original = path.read_text()
        source = (
            after / path.relative_to(before)
            if path.is_relative_to(before)
            else path
        )

        def replace(match: re.Match) -> str:
            raw = match[1]
            if raw.startswith(("https:", "http:", "mailto:", "#")):
                return match[0]
            url, separator, fragment = raw.partition("#")
            resolved = Path(os.path.abspath(path.parent / unquote(url)))
            if resolved.is_relative_to(before):
                moved = after / resolved.relative_to(before)
                return match[0].replace(
                    raw, link(source, moved) + separator + fragment
                )
            if source != path:
                return match[0].replace(
                    raw, link(source, resolved) + separator + fragment
                )
            return match[0]

        text = pattern.sub(replace, original)
        text = text.replace(
            before.relative_to(root).as_posix() + "/",
            after.relative_to(root).as_posix() + "/",
        )
        if text != original:
            outputs[path] = text
    return outputs


def archive_plan(root: Path, plan_id: str) -> None:
    root = root.resolve()
    plans = read_project(root)
    selected = [p for p in plans if p.id == plan_id]
    if not selected:
        raise WorkError(f"unknown plan: {plan_id}")
    plan = selected[0]
    if plan.path.parent.parent.name != "plans":
        raise WorkError(f"already archived: {plan_id}")
    if any(t.status != "complete" for t in plan.tasks):
        raise WorkError(f"incomplete tasks prevent archive: {plan_id}")
    before = plan.path.parent
    after = safe_path(root, root / "project/archive" / before.name)
    if after.exists():
        raise WorkError(f"archive destination exists: {after}")
    # Precompute/validate edits before the first mutation; roll back write errors.
    updates = rewritten_links(root, before, after)
    inventory = safe_path(root, root / ".harness/release-files.json")
    if inventory.is_file():
        managed = json.loads(inventory.read_text())
        if not isinstance(managed, list) or any(
            not isinstance(name, str) for name in managed
        ):
            raise WorkError("invalid release inventory; archive not performed")
        conflicts = [
            p for p in updates if p.relative_to(root).as_posix() in managed
        ]
        if conflicts:
            raise WorkError(
                "managed link needs reviewed harness update; archive refused"
            )
    updates[plan.path] = updates.get(plan.path, plan.path.read_text()).replace(
        f"- **Status:** {plan.status}", "- **Status:** complete", 1
    )
    originals = {p: p.read_text() for p in updates}
    index_paths = [
        root / "project/README.md",
        root / "project/plans/README.md",
        root / "project/archive/README.md",
        *[p.path for p in plans],
    ]
    for path in index_paths:
        safe_path(root, path)
        if path.is_file():
            originals.setdefault(path, path.read_text())
    absent = [p for p in index_paths if not p.exists()]
    after.parent.mkdir(parents=True, exist_ok=True)
    before.rename(after)
    try:
        for path, text in updates.items():
            target = (
                after / path.relative_to(before)
                if path.is_relative_to(before)
                else path
            )
            target.write_text(text)
        sync_indexes(root)
    except Exception:
        # Restore only this operation's edits, never remove unrelated contents.
        after.rename(before)
        for path, text in originals.items():
            path.write_text(text)
        for path in absent:
            if path.is_file():
                path.unlink()
        raise
